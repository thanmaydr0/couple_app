import { encryptionRequired } from '@/features/e2ee/runtime';

// Feature-local types until the shared schema is regenerated by its owner.
export const capsuleDb = supabase as SupabaseClient;
export const capsuleTiming = { poll: 30_000, holdHeartbeat: 500, notificationCooldown: 60_000 };
export async function loadCapsules(user: string) {
  const [received, authored, clock] = await Promise.all([
    capsuleDb.rpc('capsule_stubs'),
    capsuleDb.from('capsules').select('*').eq('author_id', user).order('unlock_at'),
    capsuleDb.rpc('capsule_clock'),
  ]);
  if (received.error || authored.error || clock.error) throw new Error('Capsules could not be refreshed. Try again when connected.');
  return { received: (received.data ?? []) as CapsuleStub[], authored: ((authored.data ?? []) as Capsule[]).map(projectCapsule), serverNow: clock.data as string };
}
export async function readCapsule(id: string): Promise<Capsule> {
  const { data, error } = await capsuleDb.from('capsules').select('*').eq('id', id).single();
  if (error) throw new Error('This capsule is still sealed or unavailable.');
  return projectCapsule(data as Capsule);
}
export async function holdCapsule(id: string, holding: boolean): Promise<boolean> {
  const { data, error } = await capsuleDb.rpc('capsule_hold', { capsule: id, holding });
  if (error) throw new Error('The seal could not be opened. Reconnect and try again.');
  return data === true;
}
export async function pickPhotos(remaining: number): Promise<string[]> {
  const permission = await ImagePicker.requestMediaLibraryPermissionsAsync();
  if (!permission.granted) throw new Error('Allow photo access in Android settings to attach photos.');
  const picked = await ImagePicker.launchImageLibraryAsync({ mediaTypes: ['images'], allowsMultipleSelection: true, selectionLimit: remaining });
  if (picked.canceled) return [];
  const photos: string[] = [];
  for (const asset of picked.assets.slice(0, remaining)) {
    const context = ImageManipulator.manipulate(asset.uri);
    if (Math.max(asset.width, asset.height) > 1600) context.resize(asset.width >= asset.height ? { width: 1600 } : { height: 1600 });
    const rendered = await context.renderAsync();
    try { photos.push((await rendered.saveAsync({ format: SaveFormat.JPEG, compress: 0.7 })).uri); }
    finally { rendered.release(); context.release(); }
  }
  return photos;
}
export async function saveCapsule(couple: string, user: string, draft: CapsuleDraft, photos: string[], existing?: Capsule, voice?: VoiceRecording) {
  if (await encryptionRequired(couple) || existing?.encrypted) return saveEncryptedCapsule(couple, user, draft, photos, existing, voice);
  const id = existing?.id ?? randomUUID();
  const uploaded: string[] = [];
  let created = false;
  try {
    if (!existing) {
      const result = await capsuleDb.from('capsules').insert({ id, couple_id: couple, author_id: user, ...draft });
      if (result.error) throw result.error;
      created = true;
    }
    for (const uri of photos) {
      const path = `${couple}/capsules/${id}/${randomUUID()}.jpg`;
      const bytes = decode(await FileSystem.readAsStringAsync(uri, { encoding: FileSystem.EncodingType.Base64 }));
      const result = await supabase.storage.from('capsules').upload(path, bytes, { contentType: 'image/jpeg', cacheControl: '0' });
      if (result.error) throw result.error;
      uploaded.push(path);
    }
    let voicePath = existing?.voice_path ?? null;
    if (voice) {
      voicePath = `${couple}/capsules/${id}/${randomUUID()}.m4a`;
      await uploadVoice('capsules', voicePath, voice.uri);
      uploaded.push(voicePath);
    }
    const result = await capsuleDb.from('capsules').update({ ...draft, voice_path: voicePath, media_paths: [...(existing?.media_paths ?? []), ...uploaded.filter(path => !path.endsWith('.m4a'))] }).eq('id', id).select('id').single();
    if (result.error) throw result.error;
    if (voice && existing?.voice_path && existing.voice_path !== voicePath) await supabase.storage.from('capsules').remove([existing.voice_path]).catch(() => undefined);
    return id;
  } catch {
    if (uploaded.length) await supabase.storage.from('capsules').remove(uploaded);
    if (created) await capsuleDb.from('capsules').delete().eq('id', id);
    throw new Error('Could not seal the capsule. Your draft is still here; check the connection and unlock time.');
  }
}
export async function deleteCapsule(capsule: Capsule) {
  // Clean Storage before deleting the row that authorizes object removal.
  const paths = [...capsule.media_paths, ...(capsule.voice_path ? [capsule.voice_path] : [])];
  if (paths.length) {
    const removed = await supabase.storage.from('capsules').remove(paths);
    if (removed.error) throw new Error('Could not remove capsule photos. Try again.');
  }
  const result = await capsuleDb.from('capsules').delete().eq('id', capsule.id).select('id').single();
  if (result.error) throw new Error('The capsule could not be deleted. It may already be unlocked.');
}
export function countdown(unlock: string, serverNow: string): string {
  const remaining = new Date(unlock).getTime() - new Date(serverNow).getTime();
  if (remaining <= 0) return 'Ready to open';
  const minutes = Math.ceil(remaining / 60_000);
  return minutes < 60 ? `Opens in ${minutes} min` : minutes < 1440 ? `Opens in ${Math.ceil(minutes / 60)} hours` : `Opens in ${Math.ceil(minutes / 1440)} days`;
}
